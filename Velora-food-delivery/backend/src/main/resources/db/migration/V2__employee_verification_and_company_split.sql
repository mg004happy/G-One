-- Restaurant-maintained employee roster used to verify customer affiliation.
-- Create this before the base restaurant table on fresh installations. The
-- entity mapping supplies the foreign key when Hibernate builds the base schema.
CREATE TABLE IF NOT EXISTS restaurant_employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL,
    employee_name VARCHAR(160) NOT NULL,
    employee_id VARCHAR(80) NOT NULL,
    company_name VARCHAR(120) NOT NULL,
    phone_number VARCHAR(40) NOT NULL,
    CONSTRAINT uq_restaurant_company_employee
        UNIQUE (restaurant_id, company_name, employee_id)
);

ALTER TABLE IF EXISTS orders
    ADD COLUMN IF NOT EXISTS gross_amount NUMERIC(10, 2),
    ADD COLUMN IF NOT EXISTS company_share_amount NUMERIC(10, 2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS company_name VARCHAR(120),
    ADD COLUMN IF NOT EXISTS employee_id_snapshot VARCHAR(80),
    ADD COLUMN IF NOT EXISTS restaurant_employee_id BIGINT;

-- Preserve the previous order totals when upgrading an installation that used
-- the old 10% discount. Existing orders remain historical records, not new splits.
DO $$
BEGIN
    IF to_regclass('public.orders') IS NOT NULL THEN
        IF EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = 'orders' AND column_name = 'discount_amount'
        ) THEN
            EXECUTE 'UPDATE orders SET gross_amount = total_amount + COALESCE(discount_amount, 0) WHERE gross_amount IS NULL';
        ELSE
            UPDATE orders SET gross_amount = total_amount WHERE gross_amount IS NULL;
        END IF;
        UPDATE orders SET company_share_amount = 0 WHERE company_share_amount IS NULL;

        IF to_regclass('public.restaurant_employees') IS NOT NULL
           AND NOT EXISTS (
               SELECT 1 FROM pg_constraint WHERE conname = 'fk_order_restaurant_employee'
           ) THEN
            ALTER TABLE orders ADD CONSTRAINT fk_order_restaurant_employee
                FOREIGN KEY (restaurant_employee_id) REFERENCES restaurant_employees(id) ON DELETE SET NULL;
        END IF;
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_restaurant_employee_company_id_ci
    ON restaurant_employees (restaurant_id, LOWER(company_name), LOWER(employee_id));

-- Remove the old promotional discount columns after preserving prior gross
-- totals above; new tie-up orders use company_share_amount instead.
ALTER TABLE IF EXISTS orders
    DROP COLUMN IF EXISTS discount_amount,
    DROP COLUMN IF EXISTS discount_company;
